#pragma once

#include <stdbool.h>

/*
 * Запускає окрему задачу FreeRTOS, яка:
 *  - підключається до Wi-Fi (STA), публікуючи статус у app_state;
 *  - при втраті зв'язку - перепідключається з експоненційним backoff
 *    (2с -> 4с -> ... -> максимум 60с), не блокуючи решту системи;
 *  - після CONFIG_ALERTINUA_AUTO_PROVISION_AFTER_FAILURES невдалих спроб
 *    поспіль - автоматично переходить у режим налаштування (SoftAP),
 *    так само, як і ручний виклик через довге натискання кнопки.
 *
 * Викликати один раз з app_main().
 */
void wifi_manager_task_start(void);

/*
 * Ручний перехід у режим налаштування Wi-Fi (SoftAP "ESP32-Setup" + сторінка
 * http://192.168.4.1/). Викликається з довгого натискання кнопки (button.c)
 * незалежно від поточного стану wifi_task. Після збереження нових даних
 * пристрій сам робить esp_restart().
 */
void wifi_manager_start_provisioning(void);
