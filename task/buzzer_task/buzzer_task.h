#pragma once
#include <stdint.h>

/*
 * Зумер керується власною задачею FreeRTOS через невелику командну чергу.
 * Це замінює попередню реалізацію, де buzzer_play_siren() блокувала
 * викликаючу задачу (та, відповідно, увесь main.c) на ~10 секунд у циклі
 * з 100 ітерацій, з якого не було жодного способу вийти достроково.
 *
 * buzzer_task_start() створює задачу один раз при старті системи.
 * buzzer_start_alarm()/buzzer_stop_alarm() лише кладуть команду в чергу
 * і миттєво повертаються - викликати їх можна з будь-якої задачі (render_task
 * при появі/зникненні тривоги), не блокуючись.
 */

void buzzer_task_start(void);

void buzzer_start_alarm(void); // почати сирену (з обмеженням часу, див. Kconfig)
void buzzer_stop_alarm(void);  // негайно зупинити сирену
void buzzer_beep(uint32_t freq_hz, uint32_t duration_ms); // короткий одноразовий сигнал (напр. підтвердження)
