#pragma once
#include "freertos/FreeRTOS.h"
#include "freertos/queue.h"

/*
 * autonomy_task: автономна робота від акумулятора через deep sleep.
 *
 *  - Після ввімкнення чи пробудження пристрій працює як звичайно, але якщо
 *    CONFIG_ALERTINUA_AUTONOMY_IDLE_SEC (15) секунд не натискали кнопку -
 *    вимикає дисплей і засинає (deep sleep). Поки звучить сирена або
 *    відкритий режим налаштування Wi-Fi, сон відкладається.
 *  - Натискання кнопки BOOT будить пристрій у звичайний режим.
 *  - Уві сні пристрій раз на CONFIG_ALERTINUA_AUTONOMY_POLL_SEC прокидається
 *    по таймеру і, не вмикаючи дисплей, опитує API. Якщо у вибраній області
 *    почалась тривога (до сну її не було) - прокидається повністю: мапа на
 *    дисплеї + сирена (CONFIG_ALERTINUA_SIREN_MAX_SEC, 5с). Інакше - знову
 *    засинає. Стан "тривога була" зберігається в RTC-пам'яті між снами,
 *    тож одна тривога будить пристрій лише раз.
 *
 * Без CONFIG_ALERTINUA_AUTONOMY_ENABLE усі функції нічого не роблять.
 */

/*
 * Викликати з app_main() після nvs_flash_init()/app_state_init() і
 * створення alert_queue, але ДО старту решти задач (дисплей, підсвітка,
 * кнопка). Після пробудження таймером робить перевірку API і або засинає
 * знову (не повертається), або кладе результат у alert_queue і повертається -
 * далі звичайний старт, render_task одразу малює тривогу.
 */
void autonomy_handle_wakeup(QueueHandle_t alert_queue);

/* Запускає задачу-таймер бездіяльності. Викликати після старту решти задач. */
void autonomy_task_start(void);

/* Користувач щось зробив (натискання кнопки) - відлік до сну починається знову. */
void autonomy_notify_activity(void);
